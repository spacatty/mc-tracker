export type TranslationKey = keyof typeof dictionary.en;

export function normalizeLocale(value: unknown): Locale {
  return value === "ru" ? "ru" : defaultLocale;
}

export function t(locale: Locale, key: TranslationKey) {
  return dictionary[locale][key] || dictionary.en[key];
}

export function roleLabel(locale: Locale, role: "owner" | "editor" | "viewer") {
  if (role === "owner") return t(locale, "owner");
  if (role === "editor") return t(locale, "editorRole");
  return t(locale, "viewerRole");
}

/** Russian plural form for a count: pluralRu(5, "запись", "записи", "записей") → "записей". */
export function pluralRu(n: number, one: string, few: string, many: string) {
  const abs = Math.abs(Math.trunc(n));
  const mod10 = abs % 10;
  const mod100 = abs % 100;
  if (mod10 === 1 && mod100 !== 11) return one;
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return few;
  return many;
}

/**
 * "5 entries" / "5 записей" with the right plural form in both languages.
 * count(locale, 2, { one: "entry", other: "entries", ru: ["запись", "записи", "записей"] }) → "2 entries" / "2 записи".
 */
export function count(locale: Locale, n: number, forms: { one: string; other: string; ru: [string, string, string] }) {
  if (locale === "ru") return `${n} ${pluralRu(n, ...forms.ru)}`;
  return `${n} ${n === 1 ? forms.one : forms.other}`;
}
